    public result() {
        initComponents();
        int ethicalCount = 0;
        int unethicalCount = 0;
        for (hahaha.EthicsCase c : hahaha.mainMenu.cases) {
            if (c != null && c.getVerdict() != null) {
                String choice = c.getVerdict().getStudentVerdict();
            if ("Ethical".equalsIgnoreCase(choice)) {
                ethicalCount++;
            } else if ("Unethical".equalsIgnoreCase(choice)) {
                unethicalCount++;
        }}}
        jLabel4.setText(String.valueOf(ethicalCount));
        jLabel3.setText(String.valueOf(unethicalCount));

        String profileName="";
        String profileDesc="";

        if (unethicalCount >= 0 && unethicalCount <= 2) {
            profileName = "The Tech Optimist";
            profileDesc = "You see technology as largely a force for good. You tend to trust that companies and developers have good intentions.";
        } else if (unethicalCount > 2 && unethicalCount <= 4) {
            profileName = "The Cautious Realist";
            profileDesc = "You see both the benefits and dangers of technology. You believe progress is good, but needs rules and accountability.";
        } else if (unethicalCount > 4 && unethicalCount <= 6) {
            profileName = "The Critical Thinker";
            profileDesc = "You are skeptical of how technology is being used. You believe the tech industry needs serious reform to protect people.";
        } else if (unethicalCount > 6 && unethicalCount <= 8) {
            profileName = "The Ethics Watchdog";
            profileDesc = "You believe technology is causing more harm than good right now. You think strong laws and ethical standards are urgently needed.";
        }

        jTextArea1.setText(profileName);
        jTextArea2.setText(profileDesc);
        

    }

